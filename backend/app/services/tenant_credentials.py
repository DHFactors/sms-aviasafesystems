# ============================================================================
# Password generation
# ============================================================================

_ALPHABET = string.ascii_letters + string.digits + "!@#$%&*_-"


def generate_password(length: int = 14) -> str:
    """Cryptographically random password (>= 12 chars) with mixed char classes."""
    length = max(12, int(length or 14))
    pw = [
        secrets.choice(string.ascii_uppercase),
        secrets.choice(string.ascii_lowercase),
        secrets.choice(string.digits),
        secrets.choice("!@#$%&*_-"),
    ]
    pw += [secrets.choice(_ALPHABET) for _ in range(length - 4)]
    secrets.SystemRandom().shuffle(pw)
    return "".join(pw)


# ============================================================================
# Email availability
# ============================================================================

def check_email_available(email: str) -> Dict[str, Any]:
    """Return whether an email can be used for a new Auth account."""
    email = (email or "").strip().lower()
    if not email:
        raise ValueError("email is required")
    try:
        get_auth().get_user_by_email(email)
        return {"email": email, "available": False, "exists": True}
    except fb_auth.UserNotFoundError:
        return {"email": email, "available": True, "exists": False}


def _create_auth_user(auth, u: Dict[str, Any], tid: str) -> Dict[str, Any]:
    """Create one Auth user with role/tenant claims. Returns per-user result."""
    email = (u.get("email") or "").strip().lower()
    role = u.get("role") or "AIRLINE_ADMIN"
    password = u.get("password") or generate_password()
    full_name = (u.get("full_name") or "").strip()
    department = (u.get("department") or "").strip()
    try:
        user = auth.create_user(
            email=email,
            password=password,
            email_verified=True,
            display_name=full_name or None,
        )
        claims = {"role": role, "tenant_id": tid}
        if department:
            claims["department"] = department
        auth.update_user(user.uid, custom_claims=claims)
        doc = user_doc_from_auth_record(auth.get_user(user.uid))
        # Brand-new Auth user: the password was (re)set at creation time, so
        # stamp the freshness marker now instead of relying on a stale Auth
        # metadata field the Admin SDK does not expose.
        doc["password_updated_at"] = datetime.now(timezone.utc)
        upsert_user_doc(**doc)
        return {"email": email, "role": role, "uid": user.uid, "password": password, "status": "ok"}
    except fb_auth.EmailAlreadyExistsError:
        logger.warning(
            f"Email already exists in Firebase Auth, NOT re-creating or rotating "
            f"password: {email} (tenant={tid})"
        )
        return {"email": email, "role": role, "status": "error", "detail": "email already exists"}
    except Exception as e:
        logger.error(f"Failed to create Auth user {email}: {e}")
        return {"email": email, "role": role, "status": "error", "detail": str(e)}


# ============================================================================
# Single-user creation for an existing tenant
# ============================================================================

def create_user_for_tenant(data: Dict[str, Any], actor: Dict[str, Any]) -> Dict[str, Any]:
    """Create one tenant-scoped Auth user on an existing operator tenant.

    Applies the role/tenant/department claims to the Auth user, upserts the
    Firestore `users/{uid}` doc, appends the user record to the tenant's
    `users` list, best-effort dispatches a welcome email, and writes
    `USER_CREATED` + `USER_PASSWORD_SET` audit entries. The generated password
    is returned exactly once and never persisted. Raises `ValueError` when the
    tenant is missing, the email is already stored on the tenant, or the Auth
    creation fails (e.g. email already exists in Firebase Auth).
    """
    tid = (data.get("tenant_id") or "").strip()
    email = (data.get("email") or "").strip().lower()
    if not tid or not email:
        raise ValueError("tenant_id and email are required")

    # Duplicate check runs BEFORE Auth creation so a failed create never leaks
    # an orphan Auth user / PG row with an unsurfaced password.
    doc = _read_tenant(tid)  # raises ValueError when the tenant is missing
    users = list(doc.get("users") or [])
    if any((u.get("email") or "").strip().lower() == email for u in users):
        raise ValueError("email already exists on tenant")

    auth = get_auth()
    result = _create_auth_user(auth, {
        "email": email,
        "role": data.get("role") or "AIRLINE_ADMIN",
        "full_name": data.get("full_name") or "",
        "department": data.get("department") or "",
    }, tid)
    if result.get("status") != "ok":
        raise ValueError(result.get("detail") or "could not create user")

    now = datetime.now(timezone.utc)
    full_name = (data.get("full_name") or "").strip()
    department = (data.get("department") or "").strip()
    rec = {
        "email": result["email"],
        "role": result["role"],
        "uid": result.get("uid"),
        "full_name": full_name,
        "department": department,
        "status": "active",
        "created_at": now.isoformat(),
        "last_login": None,
    }

    users.append(rec)
    prev_audit = doc.get("audit") or {}
    _patch_tenant(tid, {
        "users": users,
        "audit": {
            "created_by": prev_audit.get("created_by"),
            "created_at": prev_audit.get("created_at"),
            "last_modified_by": actor.get("email") or actor.get("uid"),
            "last_modified_at": now.isoformat(),
        },
    })

    contact = doc.get("contact") or {}
    context = {
        "contact_name": full_name or contact.get("name") or "Safety Team",
        "tenant_name": doc.get("name") or tid,
        "admin_email": email,
        "password": result["password"],
        "login_url": settings.APP_LOGIN_URL,
        "support_email": settings.APP_SUPPORT_EMAIL,
    }
    try:
        delivery = send_welcome_email(email, context)
    except Exception as e:
        logger.warning(f"Welcome email for {email} failed: {e}")
        delivery = {"sent": False, "provider": "none", "to": email, "error": str(e)}

    production_seed._audit(
        "USER_CREATED", actor, tid,
        f"Created user {email} (role={result['role']}, dept={department or 'n/a'})",
        tenant_id=tid,
        metadata={"source": "route:admin.create_user_for_tenant", "target_uid": result.get("uid")},
    )
    production_seed._audit(
        "USER_PASSWORD_SET", actor, tid,
        f"Initial password set for {email} (uid={result.get('uid')})",
        tenant_id=tid,
        metadata={"source": "route:admin.create_user_for_tenant", "target_uid": result.get("uid")},
    )
    logger.info(f"User {email} created for tenant {tid} by {actor.get('uid')}")
    return {
        "tenant_id": tid,
        "email": result["email"],
        "uid": result.get("uid"),
        "role": result["role"],
        "password": result["password"],
        "delivery": delivery,
    }


# ============================================================================
# Credentials read / admin user resolution
# ============================================================================

def _read_tenant(tid: str) -> Dict[str, Any]:
    """Return the tenant row as a document; raise when missing."""
    data = pg.fetch_by(Tenant, "slug", tid)
    if data is None:
        raise ValueError(f"tenant not found: {tid}")
    data.pop("id", None)
    return data


def _patch_tenant(tid: str, patch: Dict[str, Any]) -> Dict[str, Any]:
    """Merge `patch` into the tenant (PG primary) with best-effort mirror."""
    existing = _read_tenant(tid)
    existing.update(patch)
    pg.upsert(Tenant, "slug", tid, existing)
    try:
        get_db().collection(settings.FIREBASE_COLLECTION_TENANTS).document(tid).set(dict(patch), merge=True)
    except Exception as e:  # pragma: no cover - mirror best effort
        logger.warning(f"Tenant mirror write failed ({tid}): {e}")
    return existing


def _admin_user_email(tenant_doc: Dict[str, Any], tid: str) -> str:
    for u in tenant_doc.get("users") or []:
        if u.get("role") == "AIRLINE_ADMIN" and u.get("email"):
            return u["email"]
    sm = tenant_doc.get("safety_manager") or {}
    if sm.get("email"):
        return sm["email"]
    raise ValueError(f"no admin user configured for tenant '{tid}'")


def get_tenant_credentials(tid: str) -> Dict[str, Any]:
    """Return the stored credential metadata for a tenant (no passwords)."""
    data = _read_tenant(tid)
    return {
        "tenant_id": tid,
        "name": data.get("name"),
        "status": data.get("status"),
        "contact": data.get("contact"),
        "contract": data.get("contract"),
        "users": data.get("users") or [],
        "audit": data.get("audit"),
        "regulator_id": data.get("regulator_id"),
        "country": data.get("country"),
    }


