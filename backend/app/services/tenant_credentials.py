# Password reset + welcome email
# ============================================================================


def _refresh_password_mirror(uid: str) -> None:
    """Stamp ``password_updated_at`` = now on the PG users mirror row.

    Firebase Auth does not expose ``passwordUpdatedAt`` through the Admin SDK,
    so the freshness marker is captured at the moment we apply a new password
    and written to the PG ``users`` mirror. Never raises (best-effort; the
    original operation must not be blocked by the mirror write).
    """
    try:
        record = get_auth().get_user(uid)
        doc = user_doc_from_auth_record(record)
        doc["password_updated_at"] = datetime.now(timezone.utc)
        upsert_user_doc(**doc)
    except Exception as e:
        logger.warning(f"Failed to refresh PG password mirror for {uid}: {e}")


def reset_admin_password(tid: str, actor: Dict[str, Any]) -> Dict[str, Any]:
    """Reset the tenant's admin Auth password; returns it once."""
    data = _read_tenant(tid)
    email = _admin_user_email(data, tid)

    user = get_auth().get_user_by_email(email)
    password = generate_password()
    get_auth().update_user(user.uid, password=password)
    _refresh_password_mirror(user.uid)

    now = datetime.now(timezone.utc)
    _patch_tenant(tid, {"audit": {
        "created_by": (data.get("audit") or {}).get("created_by"),
        "created_at": (data.get("audit") or {}).get("created_at"),
        "last_modified_by": actor.get("email") or actor.get("uid"),
        "last_modified_at": now.isoformat(),
    }})
    production_seed._audit(
        "TENANT_PASSWORD_RESET", actor, tid,
        f"Reset admin password for {email} (uid={user.uid})",
        tenant_id=tid,
        metadata={"source": "route:admin.reset_admin_password", "target_uid": user.uid},
    )
    logger.info(f"Admin password reset for tenant {tid} by {actor.get('uid')}")
    return {"tenant_id": tid, "email": email, "password": password}


def send_welcome_email_for_tenant(tid: str, actor: Dict[str, Any]) -> Dict[str, Any]:
    """Set a fresh temporary password and email it to the tenant's admin."""
    data = _read_tenant(tid)
    email = _admin_user_email(data, tid)

    user = get_auth().get_user_by_email(email)
    password = generate_password()
    get_auth().update_user(user.uid, password=password)
    _refresh_password_mirror(user.uid)

    contact = data.get("contact") or {}
    context = {
        "contact_name": contact.get("name") or "there",
        "tenant_name": data.get("name") or tid,
        "admin_email": email,
        "password": password,
        "login_url": settings.APP_LOGIN_URL,
        "support_email": settings.APP_SUPPORT_EMAIL,
    }
    result = send_welcome_email(email, context)

    now = datetime.now(timezone.utc)
    _patch_tenant(tid, {"audit": {
        "created_by": (data.get("audit") or {}).get("created_by"),
        "created_at": (data.get("audit") or {}).get("created_at"),
        "last_modified_by": actor.get("email") or actor.get("uid"),
        "last_modified_at": now.isoformat(),
    }})
    production_seed._audit(
        "WELCOME_EMAIL_SENT", actor, tid,
        f"Welcome email to {email}: provider={result.get('provider')} sent={result.get('sent', False)}",
        tenant_id=tid,
        metadata={"source": "route:admin.send_welcome_email_for_tenant", "target_uid": user.uid},
    )
    logger.info(f"Welcome email for tenant {tid} -> {email} ({result.get('provider')})")
    return {
        "tenant_id": tid,
        "admin_email": email,
        "password": password,
        "delivery": result,
    }
