# ============================================================================
# FILE: tenant_credentials.py
# PATH: backend/app/services/tenant_credentials.py
# PURPOSE: Super-Admin tenant credentials management. Creates operator tenants,
#          checks email availability, stores contact/contract/user metadata on
#          the tenant document, and supports admin password reset +
#          welcome-email dispatch.
#
#          Single-path user provisioning policy (2026-09-14): a new tenant is
#          created WITHOUT Auth users (POST /api/v1/admin/tenants). Users are
#          always created one at a time afterwards via
#          create_user_for_tenant (POST /api/v1/admin/users = Production Setup
#          Step 3). The legacy batch path (create_tenant_with_credentials) was
#          removed on 2026-09-17 (see PASSWORD_RESET_BUG_INVESTIGATION.md).
#
#          Security model (ICAO Doc 10159 data-intelligence principles):
#          - Passwords are generated by the platform, applied directly to
#            Firebase Auth, returned to the caller exactly once, and NEVER
#            persisted anywhere.
#          - Every action is written to the `audit_logs` collection.
#          - All callers must be SUPER_ADMIN (route dependency) and the setup
#            key is required for every mutation.
# AUTHOR: AviaSAFE Systems
# ============================================================================

